const { chromium } = require("playwright");
const fs = require("node:fs");
const path = require("node:path");
const { pathToFileURL } = require("node:url");
const root=path.resolve(__dirname,"..");
const url=(name)=>pathToFileURL(path.join(root,`${name}.html`)).href;
const errors=[],results=[];
function check(value,label){if(!value)throw new Error(label);results.push(label)}
(async()=>{
  const browser=await chromium.launch({channel:"msedge",headless:true,args:["--use-fake-ui-for-media-stream","--use-fake-device-for-media-stream"]});
  const context=await browser.newContext({viewport:{width:1440,height:1100},reducedMotion:"reduce"});
  const p=await context.newPage();
  p.on("pageerror",e=>errors.push(e.message));
  await p.goto(url("index"));await p.waitForSelector(".feature");await p.waitForTimeout(1200);
  await p.screenshot({path:path.join(__dirname,"首页_桌面.png"),fullPage:true});
  check(await p.locator(".work-card").count()===3,"首页精选作品展示");
  const pages=["community","studio","publish","work","market","demand","new-demand","bids","order","academy","course","lesson","homework","live","room","broadcast","profile","wallet","messages","settings","activity","creator","admin"];
  const layoutIssues=[],brokenImages=[],brokenLinks=[];
  for(const name of pages){
    await p.goto(url(name));await p.waitForSelector("main[data-screen-label]");
    await p.evaluate(()=>Promise.all([...document.images].map(i=>i.decode().catch(()=>{}))));
    const layout=await p.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth+1,brokenImages:[...document.images].filter(i=>i.naturalWidth===0).map(i=>i.src),hrefs:[...document.querySelectorAll("a[href]")].map(a=>a.getAttribute("href")).filter(a=>a.split("?")[0].endsWith(".html"))}));
    brokenImages.push(...layout.brokenImages);
    for(const href of layout.hrefs){if(!fs.existsSync(path.join(root,href.split("?")[0])))brokenLinks.push(`${name}:${href}`)}
    await p.waitForTimeout(80);
    if(layout.overflow)layoutIssues.push(`${name}:desktop overflow`);
    if(["studio","market","room","academy","profile","order"].includes(name))await p.screenshot({path:path.join(__dirname,`${name}_桌面.png`),fullPage:true});
  }
  check(brokenImages.length===0,"全部页面图片加载完成");
  check(brokenLinks.length===0,"全部本地页面链接有效");
  check(errors.length===0,"24 页无 JavaScript 运行错误");
  await p.goto(url("community"));
  await p.getByRole("tab",{name:"广播剧",exact:true}).click();
  check(await p.locator(".work-card:visible").count()===2,"社区分类筛选");
  await p.locator('[data-search="works"]').fill("山海");
  check(await p.locator(".work-card:visible").count()===1,"社区关键词搜索");
  await p.goto(url("work"));
  await p.locator('[data-action="like"]').click();
  await p.locator('#comment-form input').fill("这一段声音很温柔，海风都听见了。");
  await p.locator('#comment-form button').click();
  check(await p.locator("#comments-list").innerText().then(t=>t.includes("海风都听见了")),"评论发布");
  await p.reload();
  check(await p.locator('[data-action="like"]').getAttribute("class").then(c=>c.includes("liked")),"点赞持久化");
  await p.goto(url("studio"));
  await p.locator('.editor-toolbar [data-action="studio-mode"][data-value="record"]').click();
  await p.locator('[data-action="record"]').click();
  await p.waitForTimeout(1300);
  if(await p.locator("#record-btn.recording").count()){
    await p.locator('[data-action="record"]').click();await p.waitForTimeout(400);
    check(await p.locator("#record-audio").isVisible(),"浏览器授权后的实际录音");
  }else check(await p.locator("#toast").innerText().then(t=>t.includes("麦克风")),"录音权限拒绝提示");
  await p.locator('[data-action="studio-mode"][data-value="video"]').click();
  await p.locator('[data-action="voice"][data-id="v2"]').click();
  check(await p.locator("#selected-voice").innerText().then(t=>t.includes("晚棠")),"音色选择");
  await p.locator('[data-action="generate"]').click();
  await p.getByRole("link",{name:"去发布"}).waitFor();
  await p.getByRole("link",{name:"去发布"}).click();
  await p.locator('[name="title"]').fill("高保真验证作品");
  await p.locator('[name="agreement"]').check();
  await p.locator('#publish-form button[type="submit"]').click();
  await p.getByRole("link",{name:"查看我的作品"}).click();
  check(await p.locator("main").innerText().then(t=>t.includes("高保真验证作品")),"生成到发布及个人作品闭环");
  const file={name:"试音.wav",mimeType:"audio/wav",buffer:fs.readFileSync(path.join(root,"assets/voice-demo.wav"))};
  await p.goto(url("demand"));
  await p.locator('[data-action="bid"]').click();
  await p.locator('#bid-form input[type="checkbox"]').check();
  await p.locator("#bid-form button[type=submit]").click();
  check(await p.locator("#bid-form .error-message").innerText().then(t=>t.includes("上传")),"投标缺少样音校验");
  await p.locator("#bid-file").setInputFiles(file);
  await p.locator('[name="price"]').fill("450");
  await p.locator("#bid-form button[type=submit]").click();
  await p.getByRole("link",{name:"查看我的投标"}).click();
  check(await p.locator("main").innerText().then(t=>t.includes("报价 ¥450")),"样音投标及记录保存");
  await p.goto(url("bids"));
  await p.locator('[data-action="select-bid"]').first().click();
  await p.locator("#pay-agreement").check();await p.locator("#pay-confirm").click();
  await p.getByRole("link",{name:"查看订单",exact:true}).click();
  check(await p.locator("main").innerText().then(t=>t.includes("治愈系短剧")&&t.includes("¥450.00")&&t.includes("¥382.50")),"候选合作、订单报价及佣金保持一致");
  await p.goto(url("order"));
  await p.locator('[data-action="deliver"]').click();
  await p.locator("#delivery-file").setInputFiles(file);
  await p.locator('#delivery-form textarea').fill("干音已经完成，供您验收试听。");
  await p.locator("#delivery-form button[type=submit]").click();
  await p.getByRole("link",{name:"查看订单",exact:true}).click();
  await p.locator('[data-action="accept-order"]').click();
  await p.locator('[data-action="confirm-accept"]').click();
  await p.waitForSelector('[data-screen-label="订单履约"]');
  check(await p.locator("main").innerText().then(t=>t.includes("验收完成 · 已结算")),"交付到验收结算闭环");
  await p.goto(url("course"));
  await p.locator('[data-action="purchase-course"]').click();
  await p.locator("#pay-confirm").click();
  check(await p.locator("#pay-error").innerText().then(t=>t.length>0),"支付约定确认校验");
  await p.locator("#pay-agreement").check();await p.locator("#pay-confirm").click();
  await p.getByRole("link",{name:"开始学习",exact:true}).click();
  check(p.url().includes("lesson.html"),"课程购买到学习权益");
  await p.goto(url("homework"));
  await p.locator("#homework-file").setInputFiles(file);
  await p.locator('#homework-form textarea').fill("第二种情绪想听老师建议。");
  await p.locator("#homework-form button[type=submit]").click();
  await p.getByRole("link",{name:"查看提交记录"}).click();
  check(await p.locator("main").innerText().then(t=>t.includes("试音.wav")),"作业上传与记录");
  await p.goto(url("room"));
  await p.locator("#chat-form input").fill("今晚的故事很好听");
  await p.locator("#chat-form button").click();
  check(await p.locator("#chat-messages").innerText().then(t=>t.includes("今晚的故事很好听")),"直播文字互动");
  await p.locator('[data-action="gift"]').click();
  await p.locator('[data-action="select-gift"][data-name="爆灯"]').click();
  await p.locator('[data-action="gift-pay"]').click();
  await p.locator("#pay-agreement").check();await p.locator("#pay-confirm").click();
  check(await p.locator("#chat-messages").innerText().then(t=>t.includes("爆灯")),"礼物选择与演示支付");
  for(const width of [390,360]){
    await p.setViewportSize({width,height:844});
    for(const name of ["index","community","studio","market","demand","new-demand","order","academy","course","lesson","homework","live","room","broadcast","profile","wallet","messages","settings","activity","admin"]){
      await p.goto(url(name));await p.waitForSelector("main[data-screen-label]");
      const overflow=await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
      if(overflow)layoutIssues.push(`${name}:${width} overflow`);
      if(width===390&&["index","studio","market","room","course"].includes(name))await p.screenshot({path:path.join(__dirname,`${name}_手机.png`),fullPage:true});
    }
  }
  check(layoutIssues.length===0,`桌面和 360/390px 手机无页面横向溢出${layoutIssues.length?": "+layoutIssues.join(", "):""}`);
  check(errors.length===0,"全部交互无 JavaScript 运行错误");
  await p.goto(url("index"));await p.evaluate(()=>localStorage.removeItem("yusheng-prototype-v1"));
  await p.setViewportSize({width:1440,height:1000});await p.reload();await p.screenshot({path:path.join(__dirname,"成品首页_桌面.png"),fullPage:false});
  await p.setViewportSize({width:390,height:844});await p.reload();await p.screenshot({path:path.join(__dirname,"成品首页_手机.png"),fullPage:false});
  await browser.close();
  fs.writeFileSync(path.join(__dirname,"验证结果.json"),JSON.stringify({passed:results.length,results,errors,layoutIssues,brokenImages,brokenLinks},null,2));
  console.log(JSON.stringify({passed:results.length,results,errors,layoutIssues},null,2));
})().catch(e=>{console.error(e);process.exit(1)});
